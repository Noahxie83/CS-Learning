/*
一个程序或算法的时间效率,也称“时间复杂度”,有时简称“复杂度”
复杂度常用大的字母0和小写字母n来表示,比如O(n),O(n^2)等。n代表问题的规模
时间复杂度是用算法运行过程中,某种时间固定的操作需要被执行的次数和n的关系来度量的。
   e.g.在无序数列中查找某个数,复杂度是O(n)
计算复杂度时，只统计执行次数最多的(n足够大时)那种固定操作的次数。
比如某个算法需要执行加法n^2次,除法n次,其复杂度为O(n^2)
复杂度有"平均复杂度"和"最坏复杂度"两种,两种可能一致,也可能不一致
常见复杂度度:
O(1) O(log(n)) O(n) O(n^k) O(a^n) O(n!)
*/